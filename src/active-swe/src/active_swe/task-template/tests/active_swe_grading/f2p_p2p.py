"""Compute per-test-case FAIL_TO_PASS and PASS_TO_PASS from before/after test logs.

Ported from build_f2p_p2p_xp.py. Uses log_parsers to extract per-test
pass/fail status from before_patch and after_patch logs, then classifies
each test into:
  - FAIL_TO_PASS:   before FAILED/ERROR → after PASSED
  - XFAIL_TO_PASS:  before XFAIL → after PASSED/XPASS
  - PASS_TO_PASS:   before PASSED → after PASSED/XFAIL
"""

import json
import logging
import re
from typing import Dict, List, Optional, Set

from .log_parsers import parse_test_output

logger = logging.getLogger(__name__)


# Judge if a test result name looks like a file path rather than a test case name
_FILE_PATH_RE = re.compile(r'.*/.*\.\w{1,6}$')

_PASSED_STATUSES = frozenset(("PASSED", "XFAIL", "XPASS"))
_FAILED_STATUSES = frozenset(("FAILED", "ERROR"))


def _is_file_level_entry(name: str) -> bool:
    """Check if a test result entry is a file path rather than a test case name."""
    if name.startswith('__'):
        return False  # special markers like __suite_fail__:path
    return bool(_FILE_PATH_RE.match(name))


def _is_placeholder_name(name: str) -> bool:
    """Check if a test name is a placeholder generated by log parsers rather than
    a real test case name. Placeholders start with '_' (e.g. '_phpunit_tests_failed_',
    '_summary_3_tests_f2p_', '_jest_summary_5_passed_', '_go_build_failed_pkg')
    but internal keys like '__suite_fail__:path' and '__file_test_map__' are not
    placeholder test names (they are handled by _expand_suite_fails).
    """
    if name.startswith('__'):
        return False  # internal markers, handled separately
    return name.startswith('_')


def _is_go_package_path(name: str) -> bool:
    """Check if a test result name is a Go package import path rather than a test function.

    Go package paths look like 'github.com/user/repo/pkg' or 'example.org/project/pkg'.
    They contain '/' and start with a domain-like prefix, unlike test function names
    which start with Test/Benchmark/Example/Fuzz in Go.
    """
    if name.startswith(('Test', 'Benchmark', 'Example', 'Fuzz')):
        return False
    if name == 'command-line-arguments':
        return True
    if '/' not in name:
        return False
    if re.search(r'\.\w{1,6}$', name) and '::' in name:
        return False
    if re.search(r'\.(py|js|ts|rb|php|rs|go|java|c|cpp|h|jsx|tsx|json|yaml|yml|toml|xml|html|css|md|txt)\b', name):
        return False
    if name.startswith(('./', '../')):
        return True
    if re.match(r'^[a-z0-9][\w.-]*\.', name):
        return True
    _non_go_slash_patterns = frozenset({
        'if/else', 'try/catch', 'on/off', 'yes/no', 'client/server',
        'read/write', 'input/output', 'send/receive', 'up/down',
    })
    if name.lower() in _non_go_slash_patterns:
        return False
    if re.match(r'^[a-z][\w-]+/[a-z][\w-]+$', name) and '-' in name and '::' not in name and ' > ' not in name:
        return True
    return False


def _is_noise_entry(name: str) -> bool:
    """Check if a test result name is noise that should be filtered out.

    This catches entries that are not real test function names but leaked into
    the status map from log parser artifacts: JSON log lines, bullet characters, etc.

    IMPORTANT: Some frameworks use # as part of test names (e.g. Django ticket
    references like "#24282 - Model changes..."), so # is NOT treated as noise.
    Similarly, single-quote can start Django test names like
    "'Save as new' should raise PermissionDenied...", so those are allowed.
    """
    if name.startswith('{"') or name.startswith('"level"'):
        return True
    if name.startswith("'"):
        if len(name) > 10 and ' ' in name[1:20] and not name.startswith("'use "):
            return False
        return True
    if name and not name[0].isalnum() and name[0] not in ('_', '/', '.', '-', ':', '#', '$', '[', '(', '`'):
        return True
    return False


def _expand_suite_fails(
    before_status_map: Dict[str, str],
    after_status_map: Dict[str, str],
) -> None:
    """Expand __suite_fail__:filepath markers in before_status_map.

    When a test suite failed to run entirely (e.g. Jest "Test suite failed to run"),
    the parser emits __suite_fail__:filepath → FAILED. This function looks up the
    file_test_map from the after log to find which test cases belong to that file,
    and adds them as individual FAILED entries in before_status_map.

    Also expands __suite_pass__:filepath markers in after_status_map using the same
    file_test_map, adding individual PASSED entries.
    """
    # Extract file_test_map from after status map (set by Jest/Vitest parser)
    file_test_map_raw = after_status_map.pop('__file_test_map__', None)
    after_file_map = {}
    if file_test_map_raw:
        try:
            after_file_map = json.loads(file_test_map_raw)
        except (json.JSONDecodeError, TypeError):
            pass

    # Also extract from before status map (may have file context too)
    before_file_map_raw = before_status_map.pop('__file_test_map__', None)
    before_file_map = {}
    if before_file_map_raw:
        try:
            before_file_map = json.loads(before_file_map_raw)
        except (json.JSONDecodeError, TypeError):
            pass

    # Expand __suite_fail__:filepath in before — these files failed to run entirely
    suite_fail_keys = [k for k in before_status_map if k.startswith('__suite_fail__:')]
    for key in suite_fail_keys:
        filepath = key[len('__suite_fail__:'):]
        del before_status_map[key]

        # Find test names from after log for this file
        test_names = after_file_map.get(filepath, [])
        if not test_names:
            # Also check before log (unlikely for suite-level fail, but just in case)
            test_names = before_file_map.get(filepath, [])

        if test_names:
            for tn in test_names:
                if tn not in before_status_map:
                    before_status_map[tn] = 'FAILED'
            logger.debug(f"Expanded suite-level fail for {filepath}: {len(test_names)} test cases")
        else:
            # No test names found — keep a file-level marker as fallback
            before_status_map[filepath] = 'FAILED'

    # Expand __suite_pass__:filepath in after — these files passed but had no individual names parsed
    suite_pass_keys = [k for k in after_status_map if k.startswith('__suite_pass__:')]
    for key in suite_pass_keys:
        filepath = key[len('__suite_pass__:'):]
        del after_status_map[key]

        test_names = after_file_map.get(filepath, [])
        if test_names:
            for tn in test_names:
                if tn not in after_status_map:
                    after_status_map[tn] = 'PASSED'
        # If no test names, just drop the marker (no useful case-level info)

    # Also handle __suite_fail__ in after (rare: suite failed in after too)
    after_suite_fails = [k for k in after_status_map if k.startswith('__suite_fail__:')]
    for key in after_suite_fails:
        filepath = key[len('__suite_fail__:'):]
        del after_status_map[key]
        # Try to find test names for context, but mark as FAILED
        test_names = after_file_map.get(filepath, [])
        if test_names:
            for tn in test_names:
                if tn not in after_status_map:
                    after_status_map[tn] = 'FAILED'
        else:
            after_status_map[filepath] = 'FAILED'

    # Handle before __suite_pass__ (files that passed in before with no test names)
    before_suite_pass_keys = [k for k in before_status_map if k.startswith('__suite_pass__:')]
    for key in before_suite_pass_keys:
        filepath = key[len('__suite_pass__:'):]
        del before_status_map[key]
        test_names = before_file_map.get(filepath, [])
        if test_names:
            for tn in test_names:
                if tn not in before_status_map:
                    before_status_map[tn] = 'PASSED'

    # Expand _go_pkg_failed_ markers: replace with the real package name as FAILED
    # e.g. _go_pkg_failed_github.com/foo/bar → github.com/foo/bar = FAILED
    for status_map in (before_status_map, after_status_map):
        go_pkg_keys = [k for k in status_map if k.startswith('_go_pkg_failed_')]
        for key in go_pkg_keys:
            pkg_name = key[len('_go_pkg_failed_'):]
            del status_map[key]
            if pkg_name not in status_map:
                status_map[pkg_name] = 'FAILED'


def _remove_file_level_noise(status_map: Dict[str, str]) -> None:
    """Remove file-level entries from a status map when case-level entries exist.

    When a parser emits both a file path (e.g. 'src/__tests__/foo.test.ts') and
    individual test names from the same file, the file-level entry is redundant noise.
    This function removes file-level entries if any case-level entries are present.

    Also removes Go package import paths (e.g. 'github.com/user/repo/pkg') when
    individual test case names are present, since the package-level entry is noise.
    Also removes noise entries (JSON log lines, bullet artifacts) unconditionally.
    """
    # Always remove noise entries (JSON logs, bullet chars) — they're never valid test names
    noise_keys = [k for k in status_map if _is_noise_entry(k)]
    for k in noise_keys:
        del status_map[k]

    file_entries = {k for k in status_map if _is_file_level_entry(k)}
    go_pkg_entries = {k for k in status_map if _is_go_package_path(k)}
    removable_entries = file_entries | go_pkg_entries
    if not removable_entries:
        return

    # Check if there are any case-level entries at all
    case_entries = {k for k in status_map if not _is_file_level_entry(k) and not _is_go_package_path(k) and not k.startswith('__')}
    if not case_entries:
        return  # Only file-level/package-level entries exist — keep them as the only signal

    # Case-level entries exist — remove all file-level and Go package entries
    for k in removable_entries:
        status_map.pop(k, None)