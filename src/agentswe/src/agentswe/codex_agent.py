from __future__ import annotations

import asyncio
import shlex
import subprocess
import sys
import tempfile
from pathlib import Path

from harbor.agents.installed.base import with_prompt_template
from harbor.agents.installed.codex import Codex, CodexOptions
from harbor.environments.base import BaseEnvironment
from harbor.models.agent.context import AgentContext
from pydantic import Field

GENERATOR = Path(__file__).resolve().parent / "codex_builder" / "gen_codex_config.py"
# The evaluator sidecar runs upstream's builder role broker and writes its per-trial client token here.
DEFAULT_BROKER_URL = "http://evaluator:18083/v1"
BROKER_TOKEN_FILE = "/run/agentswe-controller/builder-token"
TOKEN_ENV = "AGENTSWE_BUILDER_API_KEY"

# Upstream builders/codex/codex_provider_agent.py SESSION_STOP_SCRIPT (inline comments omitted).
SESSION_STOP_SCRIPT = r"""
keep=" 1 "
p=$$
while [ -n "$p" ] && [ "$p" != 0 ]; do
  keep="$keep$p "
  { read -r line < "/proc/$p/stat"; } 2>/dev/null || break
  rest=${line##*) }
  set -f; set -- $rest; set +f
  p=$2
done
init_command=$(tr '\000' ' ' < /proc/1/cmdline)
case "$init_command" in
  "sh -c sleep infinity "|"/bin/sh -c sleep infinity ")
    for d in /proc/[0-9]*; do
      { read -r line < "$d/stat"; } 2>/dev/null || continue
      rest=${line##*) }
      set -f; set -- $rest; set +f
      [ "$2" = 1 ] || continue
      command=$(tr '\000' ' ' < "$d/cmdline" 2>/dev/null)
      [ "$command" = "sleep infinity " ] || continue
      keep="$keep${d#/proc/} "
    done
    ;;
esac
live=0
sweep() {
  sig=$1
  live=0
  for d in /proc/[0-9]*; do
    pid=${d#/proc/}
    case "$keep" in *" $pid "*) continue ;; esac
    { read -r line < "$d/stat"; } 2>/dev/null || continue
    rest=${line##*) }
    set -f; set -- $rest; set +f
    [ "$1" = Z ] && continue
    live=$((live + 1))
    [ "$sig" = none ] || kill -s "$sig" "$pid" 2>/dev/null
  done
}
sweep none
before=$live
rounds=0
while [ "$rounds" -lt 20 ]; do
  sweep STOP
  [ "$live" -eq 0 ] && break
  sweep KILL
  rounds=$((rounds + 1))
  sleep 0.5
done
sweep none
mkdir -p "$(dirname @@OUT@@)"
printf '{"schema_version": "agentswe-builder-session-stop/v1", "reason": "session_time_limit", "live_before": %d, "live_after": %d, "kill_rounds": %d}\n' "$before" "$live" "$rounds" > @@OUT@@
cat @@OUT@@
"""


class AgentSWECodexOptions(CodexOptions):
    context_window: int | None = Field(
        default=None,
        description="Prompt window for a builder model outside the AgentSWE-Lite catalog.",
    )
    broker_url: str = Field(
        default=DEFAULT_BROKER_URL,
        description="Builder role broker as seen from the Builder container.",
    )


class AgentSWECodex(Codex):
    """AgentSWE's Builder harness (upstream builders/codex: ProviderCodex) on Harbor 0.27.

    Codex 0.144.1 runs with the AgentSWE-Lite v1 model catalog and provider config generated by
    upstream gen_codex_config.py, and reaches the model only through the task's builder broker
    (pinned model/effort, 429 -> 503 so Codex retries); it never holds a provider key.
    ``reasoning_effort`` is the Codex catalog level (default ``max``); the builder broker pins the
    provider's own spelling from AGENTSWE_BUILDER_EFFORT.
    """

    options_model = AgentSWECodexOptions

    @staticmethod
    def name() -> str:
        return "agentswe-codex"

    def _generate_config(self, model: str, catalog_path: str, out_dir: Path) -> None:
        options = self.options
        command = [
            sys.executable, str(GENERATOR), "--model", model, "--effort", options.reasoning_effort or "max",
            "--provider-type", "broker", "--base-url", options.broker_url, "--catalog-path", catalog_path,
            "--env-key", TOKEN_ENV, "--out-dir", str(out_dir),
        ]
        if options.context_window:
            command += ["--context-window", str(options.context_window)]
        for args in (command, [sys.executable, str(GENERATOR), "--verify", str(out_dir)]):
            result = subprocess.run(args, capture_output=True, text=True)
            if result.returncode != 0:
                raise ValueError("Codex config generation failed:\n" + (result.stdout + result.stderr)[-1500:])

    @with_prompt_template
    async def run(self, instruction: str, environment: BaseEnvironment, context: AgentContext) -> None:
        if not self.model_name:
            raise ValueError("Model name is required")
        model = self.model_name.split("/")[-1]
        codex_home = self._REMOTE_CODEX_HOME.as_posix()
        remote_config = (self._REMOTE_CODEX_HOME / "config.toml").as_posix()
        remote_catalog = (self._REMOTE_CODEX_HOME / "models.json").as_posix()
        logs_dir = self.environment_logs_dir.as_posix()
        env = {"CODEX_HOME": codex_home, "CODEX_PROVIDER_API_KEY_ENV": TOKEN_ENV}

        await self._ensure_agent_owned_dir(environment, self._REMOTE_CODEX_HOME)
        await self.exec_as_agent(environment, command=f'mkdir -p "$CODEX_HOME" {shlex.quote(logs_dir)}', env=env)
        with tempfile.TemporaryDirectory(prefix="agentswe-codex-") as tmp:
            out_dir = Path(tmp)
            self._generate_config(model, remote_catalog, out_dir)
            await environment.upload_file(out_dir / "config.toml", remote_config)
            await environment.upload_file(out_dir / "model_catalog.json", remote_catalog)
        await self.exec_as_root(
            environment,
            command=f"chmod a+r {shlex.quote(remote_config)} {shlex.quote(remote_catalog)}",
        )

        cli_flags = self.build_cli_flags()
        cli_flags_arg = (cli_flags + " ") if cli_flags else ""
        output = shlex.quote(f"{logs_dir}/{self._OUTPUT_FILENAME}")
        try:
            await self.exec_as_agent(
                environment,
                command=(
                    "if [ -s ~/.nvm/nvm.sh ]; then . ~/.nvm/nvm.sh; fi; "
                    f'{TOKEN_ENV}="$(cat {BROKER_TOKEN_FILE})"; export {TOKEN_ENV}; '
                    "codex exec "
                    "--dangerously-bypass-approvals-and-sandbox "
                    "--skip-git-repo-check "
                    f"--model {shlex.quote(model)} "
                    "--json "
                    f"{cli_flags_arg}"
                    "-- "
                    f"{shlex.quote(instruction)} "
                    f"2>&1 </dev/null | tee {output}"
                ),
                env=env,
            )
        except asyncio.CancelledError:
            # Harbor's session limit cancels the wait; stop every Builder process before the freeze.
            await self._stop_session_processes(environment)
            raise
        finally:
            try:
                await self.exec_as_agent(
                    environment,
                    command=(
                        f"mkdir -p {shlex.quote(logs_dir)}\n"
                        'if [ -d "$CODEX_HOME/sessions" ]; then\n'
                        f"  rm -rf {shlex.quote(logs_dir + '/sessions')}\n"
                        f'  cp -R "$CODEX_HOME/sessions" {shlex.quote(logs_dir + "/sessions")}\n'
                        "fi"
                    ),
                    env=env,
                    timeout_sec=60,
                )
            except Exception:
                pass

    async def _stop_session_processes(self, environment: BaseEnvironment) -> None:
        evidence = shlex.quote(f"{self.environment_logs_dir.as_posix()}/session_limit_stop.json")
        try:
            await self.exec_as_root(
                environment, command=SESSION_STOP_SCRIPT.replace("@@OUT@@", evidence), timeout_sec=120
            )
        except Exception:
            self.logger.warning("session-limit process stop failed", exc_info=True)
