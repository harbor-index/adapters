"""Turn generated tasks into known-wrong submissions (verifier negative control).

Only `solution/` is rewritten, so Harbor's oracle agent submits the wrong
answer through the unmodified environment and verifier. The submission:

1. spends the real episode on invalid actions, so the true reward is 0; and
2. plants a transcript that *would* replay to reward 1, plus reward files, in
   every location the agent container can write.

A correctly isolated verifier grades the sidecar's transcript and returns 0.
"""

import argparse
import json
from pathlib import Path

from agenteval_games.adapter import DATA
from agenteval_games.runtime.engine import Session
from agenteval_games.runtime.server import canonical

SOLVE = """#!/bin/bash
# Known-wrong submission; generated by scripts/make_wrong_submission.py.
set -uo pipefail
# 1. Lose the real episode: an invalid action still consumes a turn.
for _ in $(seq 20); do
  game step 'Action: stand still' >/dev/null 2>&1 || break
done
game observe
# 2. Plant a winning transcript and rewards wherever this container can write.
for target in /game-evidence /logs/artifacts /logs/artifacts/game-evidence /logs/verifier /tests; do
  mkdir -p "$target" && cp /solution/forged-transcript.json "$target/transcript.json"
done
printf '1\\n' > /logs/verifier/reward.txt
printf '{"reward": 1}\\n' > /logs/verifier/reward.json
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--dataset-dir",
        type=Path,
        required=True,
        help="Generated tasks to rewrite in place; use a dedicated copy",
    )
    args = parser.parse_args()
    tasks = sorted(
        path.parent.parent for path in args.dataset_dir.glob("*/tests/config.json")
    )
    if not tasks:
        parser.error("No generated tasks found in " + str(args.dataset_dir))
    for task in tasks:
        config = json.loads((task / "tests/config.json").read_text())
        session = Session(config, DATA)
        for action in json.loads((task / "solution/actions.json").read_text()):
            session.step(action)
        if session.reward != 1:
            parser.error("Reference actions do not win " + task.name)
        solution = task / "solution"
        for name in ("actions.json", "solve.py"):
            (solution / name).unlink()
        (solution / "forged-transcript.json").write_bytes(
            canonical(session.transcript()) + b"\n"
        )
        (solution / "solve.sh").write_text(SOLVE)
        (solution / "solve.sh").chmod(0o755)
    print("Rewrote " + str(len(tasks)) + " solutions as known-wrong submissions")


if __name__ == "__main__":
    main()
